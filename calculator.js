function add(a, b) {
  // izvještaj: prati add operacije
  return a + b;
}

function subtract(a, b) {
  // izvještaj: prati subtract operacije
  return a - b;
}

function multiply(a, b) {
  return a * b;
}

function divide(a, b) {
  return a / b;
}

module.exports = { add, subtract, multiply, divide };
